# Day 2: My First Artificial Nuron

# Step 1: Define the input
x = int(input("Enter the input value (x): "))

# Step 2: Define the weight
w = int(input("Enter the weight value (w): "))

# Step 3: Define the bias
b = int(input("Enter the bias value (b): "))

# Step 4: Calculate the neuron's output
z = (x * w) + b

# Step 5: Display the result
print("Input:", x)
print("Weight:", w)
print("Bias:", b)
print("Neuron output:", z)